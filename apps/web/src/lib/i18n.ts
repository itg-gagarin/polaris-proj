const id: Record<MsgKey, string> = { ...coreId, ...studioId };

export const MESSAGES: Record<Locale, Record<MsgKey, string>> = { en, id };

export function translate(locale: Locale, key: MsgKey, vars?: Record<string, string | number>): string {
  let s = MESSAGES[locale][key] ?? MESSAGES.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}
